// AXI4-Stream handshake simulation for the fbank frontend.
//
// Drives the adapter with a producer that only advances when S_AXIS_TREADY is
// high, and a consumer whose M_AXIS_TREADY follows a scripted pattern: a
// warm-up window, one long stall that is deliberately deeper than the elastic
// buffer, and a bursty 2/3-duty regime afterwards. Every cycle is written to a
// VCD file, and every beat the consumer accepted is reassembled and compared
// byte for byte against a direct, non-AXI run of the same bridge.
//
// The claim this tool is allowed to make: over N cycles with M stalled cycles,
// the beats that left the adapter reconstruct the reference feature frames
// exactly, and the stall propagated to S_AXIS_TREADY instead of dropping data.
// It is not a synthesisable RTL model and does not claim cycle-accurate
// agreement with any particular AXI implementation.

#include "axi4s_adapter.h"
#include "wav_reader.h"

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <stdexcept>
#include <string>
#include <vector>

namespace {

using Feature = voice::StreamingFbank::Feature;

std::string JsonEscape(const std::string& text) {
  std::string out;
  out.reserve(text.size() + 8);
  for (char c : text) {
    switch (c) {
      case '"': out += "\\\""; break;
      case '\\': out += "\\\\"; break;
      case '\n': out += "\\n"; break;
      case '\r': out += "\\r"; break;
      case '\t': out += "\\t"; break;
      default: out += c;
    }
  }
  return out;
}

struct SinkPattern {
  std::size_t warmup_cycles = 600;
  std::size_t stall_start = 700;
  std::size_t stall_cycles = 800;
  std::size_t duty_period = 48;
  std::size_t duty_ready = 32;

  bool Ready(std::size_t cycle) const {
    if (cycle < warmup_cycles) return true;
    if (cycle >= stall_start && cycle < stall_start + stall_cycles) return false;
    return (cycle % duty_period) < duty_ready;
  }
};

struct VcdWriter {
  std::ofstream out;
  std::size_t period_ns = 10;
  bool started = false;

  void Open(const std::string& path) {
    out.open(path);
    if (!out) throw std::runtime_error("cannot write " + path);
    out << "$date\n  generated by axi4s_sim\n$end\n";
    out << "$timescale 1 ns $end\n";
    out << "$scope module axi4s_frontend $end\n";
    out << "$var wire 1 ! clk $end\n";
    out << "$var wire 1 \" s_tvalid $end\n";
    out << "$var wire 1 # s_tready $end\n";
    out << "$var wire 32 % s_tdata [31:0] $end\n";
    out << "$var wire 1 % m_tvalid $end\n";
    out << "$var wire 1 ( m_tready $end\n";
    out << "$var wire 32 ) m_tdata [31:0] $end\n";
    out << "$var wire 1 * m_tlast $end\n";
    out << "$var wire 1 + m_tuser $end\n";
    out << "$var wire 16 , fifo_level [15:0] $end\n";
    out << "$var wire 16 - beat_in_burst [15:0] $end\n";
    out << "$upscope $end\n";
    out << "$enddefinitions $end\n";
    out << "$dumpvars\n";
    out << "0!\n0\"\n0#\nb0 %\n0&\n0(\nb0 )\n0*\n0+\nb0 ,\nb0 -\n";
    out << "$end\n";
    started = true;
  }

  void Cycle(std::size_t index, const voice::Axi4sFrontend::Cycle& c) {
    const std::size_t t = index * period_ns;
    out << "#" << t << "\n";
    out << "1!\n";
    out << (c.s_tvalid ? "1\"" : "0\"") << "\n";
    out << (c.s_tready ? "1#" : "0#") << "\n";
    out << "b" << Bits(c.s_tdata) << " %\n";
    out << (c.m_tvalid ? "1%" : "0%") << "\n";
    out << (c.m_tready ? "1(" : "0(") << "\n";
    out << "b" << Bits(c.m_tdata) << " )\n";
    out << (c.m_tlast ? "1*" : "0*") << "\n";
    out << (c.m_tuser ? "1+" : "0+") << "\n";
    out << "b" << Bits(static_cast<std::uint32_t>(c.fifo_level)) << " ,\n";
    out << "b" << Bits(static_cast<std::uint32_t>(c.beat_in_burst)) << " -\n";
    out << "#" << (t + period_ns / 2) << "\n0!\n";
  }

  static std::string Bits(std::uint32_t value) {
    if (value == 0) return "0";
    std::string text;
    while (value) {
      text.push_back((value & 1U) ? '1' : '0');
      value >>= 1;
    }
    std::reverse(text.begin(), text.end());
    return text;
  }
};

std::vector<Feature> Reference(const std::vector<float>& pcm) {
  voice::BoundedFbankBridge bridge;
  std::vector<Feature> frames;
  std::size_t pos = 0;
  while (pos < pcm.size()) {
    Feature frame{};
    const auto step = bridge.Process(pcm.data() + pos, pcm.size() - pos, &frame, 1);
    if (step.samples_consumed == 0 && step.frames_written == 0) break;
    pos += step.samples_consumed;
    if (step.frames_written) frames.push_back(frame);
  }
  return frames;
}

std::uint32_t FloatBits(float value) {
  std::uint32_t bits;
  std::memcpy(&bits, &value, sizeof(bits));
  return bits;
}

}  // namespace

int main(int argc, char** argv) {
  try {
    std::string wav_path, vcd_path, json_path;
    double seconds = 0.25;
    std::size_t fifo_depth = 512;
    SinkPattern sink;
    std::size_t max_cycles = 200000;
    std::size_t vcd_cycles = 3200;
    for (int i = 1; i < argc; ++i) {
      const std::string arg = argv[i];
      const auto value = [&](const char* name) -> std::string {
        if (i + 1 >= argc) throw std::invalid_argument(std::string("missing value for ") + name);
        return argv[++i];
      };
      if (arg == "--wav") wav_path = value("--wav");
      else if (arg == "--seconds") seconds = std::stod(value("--seconds"));
      else if (arg == "--fifo-depth") fifo_depth = std::stoull(value("--fifo-depth"));
      else if (arg == "--vcd") vcd_path = value("--vcd");
      else if (arg == "--json") json_path = value("--json");
      else if (arg == "--max-cycles") max_cycles = std::stoull(value("--max-cycles"));
      else if (arg == "--vcd-cycles") vcd_cycles = std::stoull(value("--vcd-cycles"));
      else if (arg == "--stall-start") sink.stall_start = std::stoull(value("--stall-start"));
      else if (arg == "--stall-cycles") sink.stall_cycles = std::stoull(value("--stall-cycles"));
      else if (arg == "--help") {
        std::cout << "usage: axi4s_sim [--wav in.wav | --seconds 0.25] [--fifo-depth 512]\n"
                     "                 [--stall-start 700] [--stall-cycles 800]\n"
                     "                 [--vcd out.vcd] [--json out.json]\n";
        return 0;
      } else {
        std::cerr << "unknown argument: " << arg << "\n";
        return 2;
      }
    }

    std::vector<float> pcm;
    std::string source;
    if (!wav_path.empty()) {
      const voice::tool::WavClip clip = voice::tool::ReadWav(wav_path);
      pcm = clip.pcm;
      source = wav_path;
    } else {
      const std::size_t n = static_cast<std::size_t>(seconds * 16000.0);
      pcm.resize(n);
      for (std::size_t i = 0; i < n; ++i) {
        pcm[i] = static_cast<float>(0.35 * std::sin(0.017 * static_cast<double>(i)) +
                                    0.12 * std::cos(0.041 * static_cast<double>(i)));
      }
      source = "synthetic";
    }

    voice::Axi4sFrontend::Config config;
    config.fifo_depth_samples = fifo_depth;
    voice::Axi4sFrontend dut(config);

    VcdWriter vcd;
    if (!vcd_path.empty()) vcd.Open(vcd_path);

    std::vector<unsigned char> received;
    received.reserve(pcm.size() * 4);
    std::size_t produced_index = 0;
    std::size_t cycle = 0;
    std::size_t downstream_stall_cycles = 0;
    std::size_t upstream_stall_cycles = 0;
    std::size_t s_tready_low_cycles = 0;
    std::size_t max_fifo_level = 0;
    std::size_t first_s_tready_low = 0;
    std::size_t max_beat_in_burst = 0;

    for (; cycle < max_cycles; ++cycle) {
      const bool s_tvalid = produced_index < pcm.size();
      const std::uint32_t s_tdata = s_tvalid ? FloatBits(pcm[produced_index]) : 0U;
      const bool m_tready = sink.Ready(cycle);
      const auto signals = dut.Tick(s_tvalid, s_tdata, m_tready);
      if (!vcd_path.empty() && cycle < vcd_cycles) vcd.Cycle(cycle, signals);

      if (s_tvalid && signals.s_tready) ++produced_index;
      if (signals.downstream_stalled) ++downstream_stall_cycles;
      if (signals.upstream_stalled) ++upstream_stall_cycles;
      if (!signals.s_tready) {
        ++s_tready_low_cycles;
        if (first_s_tready_low == 0) first_s_tready_low = cycle;
      }
      max_fifo_level = std::max(max_fifo_level, signals.fifo_level);
      max_beat_in_burst = std::max(max_beat_in_burst, signals.beat_in_burst);

      // Reassemble every beat that actually crossed the interface.
      if (signals.m_tvalid && signals.m_tready) {
        for (std::size_t b = 0; b < 4; ++b) {
          received.push_back(static_cast<unsigned char>((signals.m_tdata >> (8 * b)) & 0xFF));
        }
      }
      if (produced_index == pcm.size() && !dut.FrameInFlight() && dut.FifoLevel() == 0) break;
    }

    const std::vector<Feature> reference = Reference(pcm);
    const std::size_t received_frames = received.size() / sizeof(Feature);
    std::size_t mismatched_values = 0;
    double max_abs_diff = 0.0;
    std::size_t compared_values = 0;
    const std::size_t compare_frames = std::min(reference.size(), received_frames);
    for (std::size_t f = 0; f < compare_frames; ++f) {
      Feature decoded{};
      std::memcpy(decoded.data(), received.data() + f * sizeof(Feature), sizeof(Feature));
      for (std::size_t b = 0; b < voice::StreamingFbank::kMelBins; ++b) {
        const double diff = std::abs(decoded[b] - reference[f][b]);
        if (diff != 0.0) ++mismatched_values;
        max_abs_diff = std::max(max_abs_diff, diff);
        ++compared_values;
      }
    }

    const std::size_t beats_per_burst = dut.beats_per_burst();
    const std::size_t beats_per_frame = dut.beats_per_frame();

    std::cout << std::fixed << std::setprecision(3);
    std::cout << "source: " << source << ", " << pcm.size() << " samples, " << cycle << " cycles, "
              << "FIFO " << fifo_depth << " samples\n";
    std::cout << "beats: " << dut.BeatsAccepted() << " in, " << dut.BeatsTransferred() << " out, "
              << "frames " << received_frames << " (reference " << reference.size() << ")\n";
    std::cout << "backpressure: " << downstream_stall_cycles << " downstream stall cycles, "
              << s_tready_low_cycles << " cycles with S_AXIS_TREADY low"
              << (first_s_tready_low ? " (first at cycle " + std::to_string(first_s_tready_low) + ")"
                                     : "")
              << ", peak FIFO " << max_fifo_level << "/" << fifo_depth << "\n";
    std::cout << "integrity: " << compared_values << " values compared, " << mismatched_values
              << " mismatched, max |diff| = " << max_abs_diff << "\n";
    std::cout << "bursts: " << beats_per_burst << " beats per 64-byte burst, " << beats_per_frame
              << " beats per feature frame\n";

    if (!json_path.empty()) {
      std::ofstream out(json_path);
      if (!out) throw std::runtime_error("cannot write " + json_path);
      out.precision(17);
      out << "{\n";
      out << "  \"status\": \"measured_axi4s_handshake\",\n";
      out << "  \"source\": \"" << JsonEscape(source) << "\",\n";
      out << "  \"samples\": " << pcm.size() << ",\n";
      out << "  \"cycles\": " << cycle << ",\n";
      out << "  \"clock_mhz\": 100,\n";
      out << "  \"tdATA_bits\": 32,\n";
      out << "  \"beat_bytes\": 4,\n";
      out << "  \"burst_bytes\": 64,\n";
      out << "  \"beats_per_burst\": " << beats_per_burst << ",\n";
      out << "  \"beats_per_frame\": " << beats_per_frame << ",\n";
      out << "  \"fifo_depth_samples\": " << fifo_depth << ",\n";
      out << "  \"sink_pattern\": {\"warmup_cycles\": " << sink.warmup_cycles
          << ", \"stall_start\": " << sink.stall_start << ", \"stall_cycles\": " << sink.stall_cycles
          << ", \"duty_period\": " << sink.duty_period << ", \"duty_ready\": " << sink.duty_ready
          << "},\n";
      out << "  \"beats_accepted\": " << dut.BeatsAccepted() << ",\n";
      out << "  \"beats_transferred\": " << dut.BeatsTransferred() << ",\n";
      out << "  \"frames_received\": " << received_frames << ",\n";
      out << "  \"frames_reference\": " << reference.size() << ",\n";
      out << "  \"downstream_stall_cycles\": " << downstream_stall_cycles << ",\n";
      out << "  \"upstream_stall_cycles\": " << upstream_stall_cycles << ",\n";
      out << "  \"s_tready_low_cycles\": " << s_tready_low_cycles << ",\n";
      out << "  \"first_s_tready_low_cycle\": " << first_s_tready_low << ",\n";
      out << "  \"max_fifo_level\": " << max_fifo_level << ",\n";
      out << "  \"max_beat_in_burst\": " << max_beat_in_burst << ",\n";
      out << "  \"compared_values\": " << compared_values << ",\n";
      out << "  \"mismatched_values\": " << mismatched_values << ",\n";
      out << "  \"max_abs_diff\": " << max_abs_diff << ",\n";
      out << "  \"samples_left_in_fifo\": " << dut.FifoLevel() << ",\n";
      out << "  \"vcd\": \"" << vcd_path << "\",\n";
      out << "  \"vcd_cycles_dumped\": " << std::min(vcd_cycles, cycle) << ",\n";
      out << "  \"non_claims\": [\n";
      out << "    \"protocol/timing model, not synthesisable RTL\",\n";
      out << "    \"TVALID is combinationally derived from the packet cursor\",\n";
      out << "    \"the VCD covers the simulated window, not a silicon capture\"\n";
      out << "  ]\n";
      out << "}\n";
      std::cout << "wrote " << json_path << "\n";
    }
    if (mismatched_values != 0 || received_frames != reference.size()) return 1;
    if (s_tready_low_cycles == 0) {
      std::cerr << "warning: backpressure never reached S_AXIS_TREADY\n";
      return 1;
    }
    return 0;
  } catch (const std::exception& e) {
    std::cerr << "axi4s_sim error: " << e.what() << "\n";
    return 1;
  }
}
