#!/usr/bin/env python3
"""Create Round-2 endpoint evaluation manifest from AISHELL-style layout.

Expected input:
  wav_root/test/**/*.wav
  transcript file: <utt-id> <text>

speech_end_s is generated by reverse-energy VAD and is NOT a human timestamp.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from endpoint_vad import estimate_speech_end_details


def load_transcripts(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        key, text = line.split(maxsplit=1)
        out[key] = text
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav-root", type=Path, required=True)
    ap.add_argument("--transcript", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--count", type=int, default=30)
    ap.add_argument("--seed", type=int, default=20261011)
    args = ap.parse_args()

    transcripts = load_transcripts(args.transcript)
    candidates = []
    for wav in args.wav_root.rglob("*.wav"):
        if wav.stem in transcripts:
            candidates.append((wav.stem, wav, transcripts[wav.stem]))

    random.Random(args.seed).shuffle(candidates)
    selected = candidates[:args.count]
    if len(selected) < args.count:
        raise RuntimeError(f"Only found {len(selected)} transcript-matched wav files")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as f:
        for uid, wav, text in selected:
            vad = estimate_speech_end_details(wav)
            if vad["speech_end_s"] is None:
                raise ValueError(f"Unestimable endpoint: {wav}")
            row = {
                "id": uid,
                "wav": str(wav.resolve()),
                "reference": text,
                "speech_end_s": vad["speech_end_s"],
                "speech_end_method": vad["speech_end_method"],
                "speech_end_status": vad["status"],
                "trailing_margin_s": vad["trailing_margin_s"],
            }
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"selected={len(selected)} output={args.output}")


if __name__ == "__main__":
    main()
