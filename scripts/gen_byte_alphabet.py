"""Generate src/byte_alphabet_table.inc from Python's NFKC definitions.

icefall's Byte-BPE alphabet maps the 256 byte values onto printable code points:
ASCII 32..126 map to themselves, every other byte maps to an NFKC-stable code
point taken in order from U+0100..U+07FF. Reproducing that mapping in C++ needs
the actual code point list, and Unicode normalisation is not something a ~60-line
detokeniser should reimplement. So the list is generated here and committed, and
tests/test_zero_alloc_evidence.py regenerates it and fails on any drift.

Usage: python scripts/gen_byte_alphabet.py [--check]
"""

import argparse
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "byte_alphabet_table.inc"
COUNT = 161  # bytes 0..31 and 127..255


def candidates():
    rows = [chr(c) for c in range(256, 2048)
            if unicodedata.normalize("NFKC", chr(c)) == chr(c)]
    if len(rows) < COUNT:
        raise RuntimeError(f"Only {len(rows)} NFKC-stable code points in range")
    return rows[:COUNT]


def render():
    rows = candidates()
    lines = [
        "// Generated by scripts/gen_byte_alphabet.py -- do not edit by hand.",
        "// NFKC-stable code points for byte values 0..31 (indices 0..31) and",
        "// 127..255 (indices 32..160), matching icefall's byte_utils alphabet.",
        "static constexpr char32_t kByteAlphabetCandidates[kByteAlphabetCandidateCount] = {",
    ]
    for start in range(0, len(rows), 8):
        chunk = rows[start:start + 8]
        body = ", ".join(f"0x{ord(ch):04X}" for ch in chunk)
        lines.append(f"    {body},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="Fail if the committed file differs instead of writing it")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"DRIFT: {OUT} does not match the generated table", file=sys.stderr)
            return 1
        print(f"byte alphabet table is current ({COUNT} code points)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({COUNT} code points)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
